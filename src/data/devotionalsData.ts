export function getTodayDevotional(dayIndex?: number): DailyDevotional {
  if (dayIndex !== undefined && DEVOTIONALS_LIBRARY[dayIndex]) {
    return DEVOTIONALS_LIBRARY[dayIndex];
  }
  const dayOfYear = Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 1000 / 60 / 60 / 24);
  return DEVOTIONALS_LIBRARY[dayOfYear % DEVOTIONALS_LIBRARY.length];
}
